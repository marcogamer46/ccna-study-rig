'use strict';
/* tools/build-data.js - bundles data/*.json into data/content.js (a plain script global).
   Run after editing any data/*.json:  node tools/build-data.js
   Keeps the runtime independent of fetch/server (works from file:// and GitHub Pages). */
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'data');
const files = ['notes', 'flashcards', 'questions', 'cheatsheet', 'tsim-scenarios'];

const out = {};
for (const name of files) {
  const f = path.join(dir, name + '.json');
  out[name] = JSON.parse(fs.readFileSync(f, 'utf8'));
}

const js = '/* Auto-generated by tools/build-data.js — do not edit by hand. */\n' +
  'window.APP_DATA = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(dir, 'content.js'), js);
console.log('wrote data/content.js (' + (js.length / 1024).toFixed(1) + ' KB)');
